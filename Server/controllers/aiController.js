import "dotenv/config";
import { GoogleGenAI } from "@google/genai";

export const generateBlogContent = async (req, res) => {
    try {
        const { title, subTitle, category } = req.body;

        if (!title) {
            return res.status(400).json({
                success: false,
                message: "Blog title is required"
            });
        }

        const ai = new GoogleGenAI({
            apiKey: process.env.GEMINI_API_KEY
        });

        const prompt = `
You are an expert blog writer.

Write a high-quality, engaging blog article based on:

Title: ${title}
Subtitle: ${subTitle || "Not provided"}
Category: ${category || "General"}

Requirements:
- Write approximately 600-800 words.
- Use clear and engaging language.
- Add useful headings and subheadings.
- Use short paragraphs.
- Provide practical information and examples.
- Do not mention that the content was generated by AI.
- Return ONLY HTML.
- Use <h2>, <h3>, <p>, <ul>, <li>, <strong> and similar HTML tags.
- Do not return markdown.
`;

        const response = await ai.models.generateContent({
            model: "gemini-2.5-flash",
            contents: prompt
        });

        const content = response.text;

        res.status(200).json({
            success: true,
            content
        });

    } catch (error) {
        console.error("AI generation error:", error);

        res.status(500).json({
            success: false,
            message: error.message || "Failed to generate content"
        });
    }
};